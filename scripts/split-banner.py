#!/usr/bin/env python3
"""Split Webbanner_Announcement.svg into the parts the renderer recombines.

    python3 scripts/split-banner.py

Reads  src/lib/assets/svg/banner.svg (the unmodified 40C3 announcement banner)
Writes src/lib/generated/banner-parts.ts

The banner is cut into its stylesheet, the frames of the six boxes, the centre
(loading bar and ruler) and the original content of each box. The logo, the
outlined wordmark and the full-size background are dropped: the renderer draws
40C3_Logo_A.svg and live text instead and paints its own background.
"""
import json
import re
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src/lib/assets/svg/banner.svg"
OUT = ROOT / "src/lib/generated/banner-parts.ts"
SVG = "http://www.w3.org/2000/svg"
NS = "{%s}" % SVG
ET.register_namespace("", SVG)

NUM = r"-?(?:\d+\.?\d*|\.\d+)"


def markup(el: ET.Element) -> str:
    s = ET.tostring(el, encoding="unicode")
    s = s.replace(' xmlns="%s"' % SVG, "")
    return re.sub(r"\s+", " ", s).strip()


def straight_bbox(el: ET.Element):
    """Bounding box of a frame path (straight segments only, absolute or relative)."""
    toks = re.findall(r"[MmLlHhVvZz]|" + NUM, el.get("d"))
    x = y = 0.0
    xs, ys = [], []
    i, cmd = 0, None
    while i < len(toks):
        t = toks[i]
        if t.isalpha():
            cmd = t
            i += 1
            if cmd in "Zz":
                continue
        rel = cmd.islower()
        c = cmd.upper()
        if c in "ML":
            a, b = float(toks[i]), float(toks[i + 1])
            i += 2
            x, y = (x + a, y + b) if rel else (a, b)
            if c == "M":
                cmd = "l" if rel else "L"
        elif c == "H":
            a = float(toks[i]); i += 1
            x = x + a if rel else a
        elif c == "V":
            a = float(toks[i]); i += 1
            y = y + a if rel else a
        xs.append(x); ys.append(y)
    return [round(min(xs), 2), round(min(ys), 2), round(max(xs), 2), round(max(ys), 2)]


def main() -> None:
    tree = ET.parse(SRC)
    root = tree.getroot()
    style = root.find(f"{NS}defs/{NS}style").text
    content = next(g for g in root.iter(f"{NS}g") if g.get("id") == "Content")
    c = list(content)
    # Order of the children in the Illustrator export (checked by bounding boxes):
    #  0 logo + outlined wordmark (dropped)
    #  1 frame L1   2 frame L3   3 frame L2 (accent)   4 pony (L3)   5 hood (L1)
    #  6, 7 X diagonals (L2)   8 frame R1   9 frame R2 (accent)   10 Mona (R1)
    #  11 rocket group: invisible inner rect, rocket, frame R3   12 swirl icon (R2)
    #  13 ruler   14 loading bar
    rocket_group = c[11]
    frames = {"L1": c[1], "L2": c[3], "L3": c[2], "R1": c[8], "R2": c[9], "R3": rocket_group[2]}
    creatures = {
        "hood": ("Hood", "L1", "bottom", [c[5]]),
        "cross": ("X", "L2", "fill", [c[6], c[7]]),
        "fringe": ("Fringe", "L3", "bottom", [c[4]]),
        "mona": ("Mona", "R1", "bottom", [c[10]]),
        "swirl": ("Swirl", "R2", "center", [c[12]]),
        "rocket": ("Rocket", "R3", "bottom", [rocket_group[0], rocket_group[1]]),
    }
    parts = {
        "style": re.sub(r"\s+", " ", style).strip(),
        "frames": {k: {"markup": markup(v), "box": straight_bbox(v)} for k, v in frames.items()},
        "center": markup(c[13]) + markup(c[14]),
        "creatures": {
            k: {"label": label, "slot": slot, "anchor": anchor, "markup": "".join(markup(e) for e in els)}
            for k, (label, slot, anchor, els) in creatures.items()
        },
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// Generated by scripts/split-banner.py from src/lib/assets/svg/banner.svg. Do not edit.\n"
        "/* eslint-disable */\n"
        f"export const bannerParts = {json.dumps(parts, indent=2, ensure_ascii=False)} as const;\n"
    )
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
